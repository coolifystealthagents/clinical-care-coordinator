function applyEditorialPolicy<T extends { slug: string }>(
  records: T[],
  curated: T[],
  archiveCanonical: string,
): T[] {
  const curatedBySlug = new Map(curated.map((record) => [record.slug, record]));
  return records.map((record) => curatedBySlug.get(record.slug) ?? {
    ...record,
    indexable: false,
    archiveCanonical,
  });
}

